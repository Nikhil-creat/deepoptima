"""Generates a standalone Python script that uses a downloaded model."""

def predict_script(exp_name: str, family_label: str, features: list[dict], sklearn_version: str, task: str) -> str:
    num = [f["name"] for f in features if f["kind"] == "numeric"]
    cat = [f["name"] for f in features if f["kind"] == "categorical"]
    return f'''"""Prediction script generated by DeepOptima Studio.
Experiment : {exp_name}
Model      : {family_label}
Task       : {task}

Setup:
    pip install "scikit-learn=={sklearn_version}" pandas joblib
Usage:
    python predict.py new_data.csv        # needs model.joblib next to this file
Output:
    predictions.csv  (your rows plus a 'prediction' column)
"""
import sys
import joblib
import pandas as pd

NUMERIC = {num!r}
CATEGORICAL = {cat!r}

model = joblib.load("model.joblib")
df = pd.read_csv(sys.argv[1] if len(sys.argv) > 1 else "new_data.csv")
df.columns = [" ".join(str(c).split()) for c in df.columns]      # same header cleaning as the website

missing = [c for c in NUMERIC + CATEGORICAL if c not in df.columns]
if missing:
    print("Warning: missing columns will be treated as empty:", missing)
    for c in missing:
        df[c] = float("nan")
for c in NUMERIC:
    df[c] = pd.to_numeric(df[c], errors="coerce")

out = df.copy()
out["prediction"] = model.predict(df[NUMERIC + CATEGORICAL])
out.to_csv("predictions.csv", index=False)
print(out.head())
'''
